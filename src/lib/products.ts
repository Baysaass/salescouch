/** Харилцагчийн мэдээлэлд хамгийн тохирох бүтээгдэхүүнүүдийг оноогоор эрэмбэлнэ */
export function matchProducts(text: string, limit = 4): Product[] {
  const t = text.toLowerCase();
  const scored = PRODUCTS.map((p) => {
    let s = 0;
    for (const k of p.keywords) if (t.includes(k)) s += 2;
    if (t.includes(p.name.toLowerCase())) s += 10;
    if (/ххк|llc|компани|байгууллага|захирал|менежер|hr/.test(t) && p.segment !== 'B2C') s += 1;
    if (p.status === 'check') s -= 1;
    return { p, s };
  })
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s);
  return scored.slice(0, limit).map((x) => x.p);
}

